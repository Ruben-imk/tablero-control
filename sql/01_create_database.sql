-- Ejecutar en SERVIDOR B.
-- Si la base ya existe, omite CREATE DATABASE.

IF DB_ID('CONTROL_PROCESOS') IS NULL
BEGIN
    CREATE DATABASE CONTROL_PROCESOS;
END
GO

USE CONTROL_PROCESOS;
GO

IF OBJECT_ID('dbo.PLANEACIONES', 'U') IS NULL
BEGIN
    CREATE TABLE dbo.PLANEACIONES (
        PLANEACION       NVARCHAR(100) NOT NULL,
        FECHA_CARGA      DATE NULL,
        PZ_PEDIDAS       INT NOT NULL CONSTRAINT DF_PLANEACIONES_PZ_PEDIDAS DEFAULT 0,
        PZ_ENVIADAS      INT NOT NULL CONSTRAINT DF_PLANEACIONES_PZ_ENVIADAS DEFAULT 0,
        ULTIMA_EDICION   DATETIME2 NULL,
        USUARIO_EDITA    NVARCHAR(100) NULL,
        STATUS           NVARCHAR(50) NULL,

        PREPARADO        NVARCHAR(20) NOT NULL
            CONSTRAINT DF_PLANEACIONES_PREPARADO DEFAULT 'Pendiente',
        VALIDADO         NVARCHAR(20) NOT NULL
            CONSTRAINT DF_PLANEACIONES_VALIDADO DEFAULT 'Pendiente',

        ACTUALIZADO_EN   DATETIME2 NOT NULL
            CONSTRAINT DF_PLANEACIONES_ACTUALIZADO DEFAULT SYSDATETIME(),

        CONSTRAINT PK_PLANEACIONES PRIMARY KEY (PLANEACION),

        CONSTRAINT CK_PLANEACIONES_PREPARADO
            CHECK (PREPARADO IN ('Pendiente', 'En proceso', 'Completo')),

        CONSTRAINT CK_PLANEACIONES_VALIDADO
            CHECK (VALIDADO IN ('Pendiente', 'En proceso', 'Completo'))
    );

    CREATE INDEX IX_PLANEACIONES_FECHA
        ON dbo.PLANEACIONES(FECHA_CARGA);

    CREATE INDEX IX_PLANEACIONES_STATUS
        ON dbo.PLANEACIONES(STATUS);

    CREATE INDEX IX_PLANEACIONES_PREPARADO
        ON dbo.PLANEACIONES(PREPARADO);

    CREATE INDEX IX_PLANEACIONES_VALIDADO
        ON dbo.PLANEACIONES(VALIDADO);
END
GO
